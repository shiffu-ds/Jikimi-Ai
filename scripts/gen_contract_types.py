"""Pydantic contracts -> JSON Schema -> TypeScript (``apps/dashboard/src/lib/contracts.gen.ts``).

    uv run python scripts/gen_contract_types.py          # write
    uv run python scripts/gen_contract_types.py --check  # CI / pre-commit: fail on drift

Response fields with defaults are emitted as required (FastAPI always serializes them).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from jikimi_contracts import SCHEMA_VERSION, exported_models
from pydantic.json_schema import GenerateJsonSchema

OUT = Path("apps/dashboard/src/lib/contracts.gen.ts")
HEADER = f"""// AUTO-GENERATED by scripts/gen_contract_types.py from packages/jikimi-contracts.
// Do not edit by hand. Schema version {SCHEMA_VERSION}.
/* eslint-disable */
"""


class ResponseSchema(GenerateJsonSchema):
    """Serialization schema where every serialized field is required (defaults included)."""

    def field_is_required(self, field: Any, total: bool) -> bool:
        if self.mode == "serialization":
            return not field.get("serialization_exclude")
        return bool(super().field_is_required(field, total))


def ts_type(s: dict[str, Any]) -> str:
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    if "anyOf" in s or "oneOf" in s:
        parts = [ts_type(x) for x in s.get("anyOf", s.get("oneOf", []))]
        return " | ".join(dict.fromkeys(parts))
    t = s.get("type")
    if isinstance(t, list):
        return " | ".join(ts_type({**s, "type": x}) for x in t)
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        if "prefixItems" in s:
            return "[" + ", ".join(ts_type(x) for x in s["prefixItems"]) + "]"
        inner = ts_type(s.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object" or "additionalProperties" in s:
        ap = s.get("additionalProperties")
        if isinstance(ap, dict) and ap:
            return f"Record<string, {ts_type(ap)}>"
        if s.get("properties"):
            return "{ " + "; ".join(f"{k}: {ts_type(v)}" for k, v in s["properties"].items()) + " }"
        return "Record<string, unknown>"
    return "unknown"


def interface(name: str, schema: dict[str, Any]) -> str:
    if "enum" in schema:
        return f"export type {name} = {ts_type(schema)};\n"
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    lines = [f"export interface {name} {{"]
    for key, prop in props.items():
        optional = key not in required and "default" not in prop
        doc = prop.get("description")
        if doc:
            lines.append(f"  /** {doc.strip().splitlines()[0]} */")
        safe = key if key.isidentifier() else json.dumps(key)
        lines.append(f"  {safe}{'?' if optional else ''}: {ts_type(prop)};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def generate() -> str:
    defs: dict[str, dict[str, Any]] = {}
    for model in exported_models():
        schema = model.model_json_schema(
            by_alias=True, ref_template="#/$defs/{model}", mode="serialization", schema_generator=ResponseSchema
        )
        for k, v in schema.pop("$defs", {}).items():
            defs.setdefault(k, v)
        defs[model.__name__] = schema
    body = "\n".join(interface(name, defs[name]) for name in sorted(defs))
    return HEADER + "\n" + body


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = generate()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date: run `uv run python scripts/gen_contract_types.py`", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({text.count('export ')} types)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
